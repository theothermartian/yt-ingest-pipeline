#!/usr/bin/env bash
# Installs the native messaging host for the YT Ingest Bookmarker Firefox extension.
# Run once after cloning. Re-run if the project is moved.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
NATIVE_HOST_DIR="$SCRIPT_DIR/native-host"
MANIFEST="$NATIVE_HOST_DIR/com.yt_ingest.bookmarker.json"
WRAPPER="$NATIVE_HOST_DIR/host_wrapper.sh"
HOST_JS="$NATIVE_HOST_DIR/yt_bookmark_host.js"
HOOK="$SCRIPT_DIR/on_bookmark.sh"
NODE_BIN="/opt/homebrew/bin/node"
FIREFOX_NM_DIR="$HOME/Library/Application Support/Mozilla/NativeMessagingHosts"
EXTENSION_ID="yt-ingest-bookmarker@local"

# ── Refuse to install in TCC-protected folders ────────────────────────────────
# macOS blocks non-FDA apps (like Firefox) from spawning processes inside
# ~/Documents, ~/Desktop, and ~/Downloads. The native host launch will fail with
# "Operation not permitted" if the project lives there.
case "$SCRIPT_DIR/" in
  "$HOME/Documents/"*|"$HOME/Desktop/"*|"$HOME/Downloads/"*)
    echo "ERROR: This project is inside a macOS TCC-protected folder:" >&2
    echo "  $SCRIPT_DIR" >&2
    echo "" >&2
    echo "Firefox cannot launch the native host from ~/Documents, ~/Desktop, or ~/Downloads" >&2
    echo "without Full Disk Access. Either:" >&2
    echo "  1. Move this project to e.g. ~/yt-ingest-pipeline (recommended), or" >&2
    echo "  2. Grant Firefox Full Disk Access in System Settings →" >&2
    echo "     Privacy & Security → Full Disk Access, then re-run this script." >&2
    exit 1
    ;;
esac

# ── Require Node at the expected absolute path ────────────────────────────────
if [ ! -x "$NODE_BIN" ]; then
  echo "ERROR: Node.js not found at $NODE_BIN" >&2
  echo "" >&2
  echo "Firefox-spawned processes have a minimal PATH, so the wrapper uses an" >&2
  echo "absolute Node path. On Apple Silicon, install via Homebrew:" >&2
  echo "  brew install node" >&2
  echo "" >&2
  echo "If your Node lives elsewhere, edit NODE_BIN at the top of this script" >&2
  echo "and the exec line in native-host/host_wrapper.sh." >&2
  exit 1
fi

# ── Rewrite host_wrapper.sh with absolute paths for this machine ─────────────
cat > "$WRAPPER" <<EOF
#!/bin/bash
# Wrapper invoked by Firefox's native messaging. Uses an absolute Node path
# because Firefox-spawned processes have a minimal PATH.
# Generated by install.sh — re-run install.sh if you move the project.
echo "\$(date -u) wrapper started" >> "$SCRIPT_DIR/host_debug.log"
exec $NODE_BIN "$HOST_JS" "\$@"
EOF
chmod +x "$WRAPPER"
echo "  Wrote wrapper: $WRAPPER"

# ── Rewrite the native messaging manifest with absolute path to wrapper ──────
cat > "$MANIFEST" <<EOF
{
  "name": "com.yt_ingest.bookmarker",
  "description": "YT Ingest Bookmarker native host",
  "path": "$WRAPPER",
  "type": "stdio",
  "allowed_extensions": [
    "$EXTENSION_ID"
  ]
}
EOF
echo "  Wrote manifest: $MANIFEST"

# ── Make scripts executable ───────────────────────────────────────────────────
chmod +x "$HOST_JS"
echo "  chmod +x $HOST_JS"

if [ -f "$HOOK" ]; then
  chmod +x "$HOOK"
  echo "  chmod +x $HOOK"
fi

# ── Install manifest where Firefox looks for it ───────────────────────────────
mkdir -p "$FIREFOX_NM_DIR"
cp "$MANIFEST" "$FIREFOX_NM_DIR/com.yt_ingest.bookmarker.json"
echo "  Installed manifest: $FIREFOX_NM_DIR/com.yt_ingest.bookmarker.json"

# ── Next steps ────────────────────────────────────────────────────────────────
cat <<EOF

Done.

Next steps:
  1. FULLY QUIT Firefox (Cmd+Q). Closing the window is not enough — Firefox
     caches the native-host registry per session.
  2. Relaunch Firefox.
  3. Open about:debugging → "This Firefox" → "Load Temporary Add-on…".
  4. Pick: $SCRIPT_DIR/extension/manifest.json
  5. Visit a YouTube video page and click the toolbar icon to test.

Bookmarks file: $SCRIPT_DIR/bookmarks.txt
Hook script:    $SCRIPT_DIR/on_bookmark.sh
Ingest log:     $SCRIPT_DIR/ingest.log

If something fails, open the Browser Console (Cmd+Shift+J) — NOT the Web
Console — to see the real native-messaging error.
EOF
